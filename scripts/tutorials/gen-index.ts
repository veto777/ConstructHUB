/**
 * The generated indexes of the help system — so that every video and every new help entry is ONE
 * FILE of its own and two producers never edit the same line:
 *
 *   shared/help/videos/<helpKey>.json   → shared/help/videos/index.ts    (the manifest, a file per video)
 *   shared/help/entries/<group>/<key>.ts → shared/help/entries/index.ts   (help entries added after the first registry)
 *   every registry entry's route fields  → shared/help/routes.ts          (key → route/parent/alsoAt/unlisted/group)
 *
 * The route table lets a page header pick its "i" (shared/help/route-match.ts) without loading the registry's
 * text; it is built from the registry itself, so it is written after the two directory indexes.
 *
 *   tsx scripts/tutorials/gen-index.ts [--check]
 *
 * Each index is one self-contained `export … from` line per file, sorted. Both are committed (the
 * client build, the server bundle, tsx and vitest all import them as plain modules) and carry
 * `merge=union` in .gitattributes: when two branches each add a line, git keeps both. If an index is
 * ever stale or conflicted, run this — it is rebuilt from the directory, never edited by hand.
 * server/help-registry.test.ts fails when an index does not match its directory.
 */
import fs from "fs";
import path from "path";
import type { HelpRouteRow } from "../../shared/help/route-match";

const ROOT = path.resolve(import.meta.dirname, "../..");
const ident = (prefix: string, name: string) => `${prefix}_${name.replace(/[^a-zA-Z0-9]/g, "_")}`;
const HEADER = (what: string) => `// GENERATED by scripts/tutorials/gen-index.ts from the files in this directory — do not edit.\n// ${what}\n`;

function walk(dir: string, ext: string, base = dir): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) =>
    d.isDirectory() ? walk(path.join(dir, d.name), ext, base)
      : d.name.endsWith(ext) && d.name !== "index.ts" ? [path.relative(base, path.join(dir, d.name)).split(path.sep).join("/")] : []);
}

/** [file, content] of both indexes, as they should be. */
export function indexes(): [string, string][] {
  const videosDir = path.join(ROOT, "shared/help/videos"), entriesDir = path.join(ROOT, "shared/help/entries");
  const videos = walk(videosDir, ".json").sort().map((f) => `export { default as ${ident("v", f.slice(0, -5))} } from "./${f}";`);
  const entries = walk(entriesDir, ".ts").sort().map((f) => `export { default as ${ident("e", path.basename(f, ".ts"))} } from "./${f.slice(0, -3)}";`);
  return [
    [path.join(videosDir, "index.ts"), `${HEADER("One line per recorded walkthrough (its manifest file).")}${videos.join("\n") || "export {};"}\n`],
    [path.join(entriesDir, "index.ts"), `${HEADER("One line per help entry file.")}${entries.join("\n") || "export {};"}\n`],
  ];
}

/** The route table's file, and its content for the registry's entries (one sorted line per entry). */
export const ROUTES_FILE = path.join(ROOT, "shared/help/routes.ts");
export function routeIndex(entries: readonly HelpRouteRow[]): string {
  const rows = entries.map((e) => {
    const row: HelpRouteRow = { key: e.key, route: e.route, group: e.group };
    if (e.parent) row.parent = e.parent;
    if (e.alsoAt?.length) row.alsoAt = [...e.alsoAt];
    if (e.unlisted) row.unlisted = true;
    return `  ${JSON.stringify(row)},`;
  }).sort();
  return `// GENERATED by scripts/tutorials/gen-index.ts from shared/help/registry.ts HELP_ENTRIES — do not edit.\n// Every help entry's route fields, so helpKeyForRouteIn (./route-match.ts) runs without the entry text.\nimport type { HelpRouteRow } from "./route-match";

export const HELP_ROUTES: readonly HelpRouteRow[] = [
${rows.join("\n")}
];
`;
}
/** The route table as it should be — imports the registry, so call it after the directory indexes are current. */
async function routeIndexNow(): Promise<[string, string]> {
  const { HELP_ENTRIES } = await import("../../shared/help/registry");
  return [ROUTES_FILE, routeIndex(HELP_ENTRIES)];
}

/** Write both indexes (atomically: producers in the same working copy may run this at the same moment). */
export function writeIndexes(): void {
  for (const [file, content] of indexes()) writeIfChanged(file, content);
}
function writeIfChanged(file: string, content: string): void {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === content) return;
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, content); fs.renameSync(tmp, file);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  if (process.argv.includes("--routes")) writeIfChanged(...(await routeIndexNow()));
  else if (process.argv.includes("--check")) {
    const stale = [...indexes(), await routeIndexNow()].filter(([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content).map(([f]) => path.relative(ROOT, f));
    if (stale.length) { console.error(`stale: ${stale.join(", ")} — run: npx tsx scripts/tutorials/gen-index.ts`); process.exit(1); }
    console.log("indexes are up to date");
  } else {
    writeIndexes();
    // A fresh process imports the registry, so it reads the entries index just written rather than a stale one.
    const { execFileSync } = await import("child_process");
    execFileSync(process.execPath, [...process.execArgv, import.meta.filename, "--routes"], { stdio: "inherit" });
    console.log("indexes written");
  }
}

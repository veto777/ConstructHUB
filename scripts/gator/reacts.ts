/**
 * "Gator Reacts" — the episode edit: fail clips with the gator cropped in, reacting at the impact, and
 * full-screen host lines between them.
 *
 * RUN
 *   npx tsx --env-file=.env.gator scripts/gator/reacts.ts docs/gator/reacts/<id>.json [--out file.mp4]
 *   npx tsx --env-file=.env.gator scripts/gator/reacts.ts docs/gator/reacts/<id>.json --owner-accepted-risk   (third-party clips; see below)
 * Writes analysis/gator-shorts/_reacts/reacts-<id>.mp4 (+ -review.jpg contact sheet, + .json sidecar) unless --out.
 *
 * THE EPISODE (docs/gator/reacts/<id>.json) — every path is relative to analysis/gator-shorts/:
 *   {
 *     "id": "ep01",
 *     "music": "sneaking-around",                              // a CC0 bed from scripts/gator/music.ts
 *     "open": "host-open",                                     // a host line: an id (its pure.mp4 / clip.mp4 / only raw take)
 *     "verdict": { "after": 2, "line": { "id": "host-write-up", "in": 0.2, "out": 2.9, "caption": "That's a write-up." } },
 *     "signOff": "host-sign-off",                              // optional
 *     "ownerAcceptedRisk": { "by": "…", "date": "2026-10-08", "quote": "…" },   // only for third-party clips
 *     "clips": [
 *       { "file": "fx-raccoon-plank/videos/s1-still1-take1.mp4",
 *         "impact": 2.6,                                       // seconds in the SOURCE file
 *         "in": 0.4, "out": 4.4,                               // optional: the range used (else impact − 2.0 … impact + 1.6;
 *                                                              //   the old relative "pre"/"post" fields still work)
 *         "crop": { "x": 656, "y": 0, "w": 608, "h": 1080 },   // optional, source pixels: cropped to this box, then a ~9:16
 *                                                              //   box fills 1080×1920, anything wider is fitted over a blur
 *         "panel": "bl",                                       // where the gator sits: bl (default), br, tl, tr
 *         "reaction": "react-shocked-01-jaw-drop",             // an id, or a file, e.g. "_deliver/reaction-shocked-01-jaw-drop.mp4"
 *         "peak": 1.9,                                         // optional: seconds into the reaction it peaks (else PEAK_AT / 0.7)
 *         "rights": { "kind": "own-ai", "record": "generated by us, Higgsfield …" } }
 *     ]
 *   }
 * A host line is either a plain id or { "id", "in", "out", "caption" } (trimmed to in…out; the caption replaces
 * the line's social.json script). The reaction's PEAK lands on the clip's IMPACT; no reaction is used twice.
 *
 * THE RIGHTS RULE — in the tool, not in a habit: every clip carries a rights record:
 *   own-ai       generated by us (the animal cast; AI-labelled)
 *   owner        filmed by the owner or his crews, with their say-so
 *   licensed     bought or licensed for commercial social use — `licensor` and `licence` (the reference) required
 *   cc-by        published under Creative Commons Attribution — `url` and `attribution` required (and credited)
 *   third-party  somebody else's video, NOT licensed — `source` (the https YouTube address) and `channel` required.
 *                Refused unless BOTH the run has --owner-accepted-risk AND the episode carries
 *                "ownerAcceptedRisk": { "by", "date" (YYYY-MM-DD), "quote" } — the owner's own words accepting the
 *                copyright / takedown / account-strike risk. Never a default. Such a run prints a warning, and
 *                the sidecar records every clip's source and channel plus a credits list "clips: <channel> (YouTube)".
 * A clip with no record, an unknown kind, or a record that admits it is unlicensed under another kind is refused.
 * See docs/gator/CLIP-LICENSING.md for how to get footage properly.
 *
 * WATERMARKS — by decision, this tool has NO watermark-removal step and never gets one: it does not remove, blur,
 * crop out or cover a creator's watermark or handle. The only lever is `panel`, which moves the gator AWAY from a
 * watermark; a `crop` must not be chosen to cut one off. A record that says it was de-watermarked is refused.
 *
 * THE EDIT: vertical 1080×1920; each clip at real speed; the gator panel (head-and-shoulders, 460×560) sits in
 * its corner for the whole clip, clear of the bottom 250 px the platforms draw over; full-screen host lines with
 * a caption; a 0.8 s logo-only end tag (never the cartoon mascot: this is a live-gator video); a CC0 music bed
 * low under the clips' own sound; −14 LUFS.
 */

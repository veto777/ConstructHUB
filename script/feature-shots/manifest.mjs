// Writes shared/feature-pages/screens.ts from script/feature-shots/shots/*.json and the captured images.
//   node script/feature-shots/manifest.mjs
// A shot whose image is missing is left out (and reported); the order is the JSON order per key.
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SHOTS = "script/feature-shots/shots", IMG = "client/public/feature-shots", OUT = "shared/feature-pages/screens.ts";
const byKey = {};
let missing = 0;
for (const file of fs.readdirSync(SHOTS).filter((f) => f.endsWith(".json")).sort()) {
  for (const s of JSON.parse(fs.readFileSync(path.join(SHOTS, file), "utf8"))) {
    if (s.skip) continue;
    const img = path.join(IMG, `${s.key}-${s.n}.webp`);
    if (!fs.existsSync(img)) { console.log(`missing ${img} (${file})`); missing++; continue; }
    if (!s.alt || !s.caption) throw new Error(`${file}: ${s.key}-${s.n} needs alt and caption`);
    const { width, height } = await sharp(img).metadata();
    const host = s.route.startsWith("/crm") ? "portal.constructhub.us" : "constructhub.us";
    const route = s.url ?? s.route;
    (byKey[s.key] ??= []).push({ n: s.n, src: `/feature-shots/${s.key}-${s.n}.webp`, alt: s.alt, caption: s.caption, url: `${host}${route === "/" ? "" : route}`, width, height });
  }
}
const body = Object.keys(byKey).sort().map((k) => {
  const list = byKey[k].sort((a, b) => a.n - b.n).map(({ n, ...rest }) => `    ${JSON.stringify(rest)},`).join("\n");
  return `  ${JSON.stringify(k)}: [\n${list}\n  ],`;
}).join("\n");
fs.writeFileSync(OUT, `/**
 * GENERATED by script/feature-shots/manifest.mjs — do not edit by hand.
 * Screens of each feature in the app, captured from a sample account in a throwaway lane
 * (script/feature-shots/README.md). The feature page labels every one "Sample data".
 */
import type { FeatureScreen } from "./types";

export const FEATURE_SCREENS: Readonly<Record<string, readonly FeatureScreen[]>> = {
${body}
};
`);
console.log(`${OUT}: ${Object.keys(byKey).length} pages, ${Object.values(byKey).flat().length} screens${missing ? `, ${missing} missing` : ""}`);

/**
 * Adapter registry: platform label (or alias) → PortalAdapter.
 *
 * The seven adapters that live in server/scraper.ts predate this interface.
 * They are wrapped here with `listRecent` returning [] and
 * `capabilities.listRecent = false`; platform-specific adapter files under
 * server/scrapers/ replace these wrappers by calling `registerAdapter`.
 */
import { scrapeByPlatform, type ScrapeResult } from "../scraper";
import type { AdapterCtx, PermitRecord, PermitSearchType, PortalAdapter } from "./types";

const adapters = new Map<string, PortalAdapter>();

function key(platform: string): string {
  return platform.trim().toLowerCase();
}

/** Register (or replace) an adapter under its platform label and aliases. */
export function registerAdapter(adapter: PortalAdapter): void {
  adapters.set(key(adapter.platform), adapter);
  for (const alias of adapter.aliases ?? []) adapters.set(key(alias), adapter);
}

export function getAdapter(platform: string | null | undefined): PortalAdapter | null {
  if (!platform) return null;
  return adapters.get(key(platform)) ?? null;
}

/** Distinct adapters, for capability listings. */
export function listAdapters(): PortalAdapter[] {
  return Array.from(new Set(adapters.values()));
}

/** Every lower-cased platform label/alias with an adapter, sorted. */
export function listPlatformLabels(): string[] {
  return Array.from(adapters.keys()).sort();
}

// Jurisdiction-specific adapters (official open-data feeds keyed by the catalog's
// "City, ST" / "X County, ST" string). They beat the platform adapter: the bulk feed
// is cheaper and lists by date, which the alerts poller needs.
const byJurisdiction = new Map<string, PortalAdapter>();

export function registerJurisdictionAdapter(jurisdiction: string, adapter: PortalAdapter): void {
  byJurisdiction.set(key(jurisdiction), adapter);
}

export function getJurisdictionAdapter(jurisdiction: string | null | undefined): PortalAdapter | null {
  if (!jurisdiction) return null;
  return byJurisdiction.get(key(jurisdiction)) ?? null;
}

export function listAdapterJurisdictions(): string[] {
  return Array.from(byJurisdiction.keys()).sort();
}

/** The adapter for a permit_databases row: jurisdiction feed first, then the platform label (or alias). */
export function getAdapterFor(row: { platform: string | null | undefined; jurisdiction?: string | null }): PortalAdapter | null {
  return getJurisdictionAdapter(row.jurisdiction) ?? getAdapter(row.platform);
}

type LegacyAdapter = PortalAdapter & { legacy: true };

/** True for the server/scraper.ts wrappers below; scrapeByPlatform keeps routing those through its own switch. */
export function isLegacyAdapter(adapter: PortalAdapter): boolean {
  return (adapter as Partial<LegacyAdapter>).legacy === true;
}

/** Source of shared/scrapable-platforms.ts (scripts/sync-scrapable-platforms.ts writes it; registry.test.ts checks it). */
export function renderScrapablePlatformsModule(opts: { excludeJurisdictions?: string[] } = {}): string {
  const skip = new Set((opts.excludeJurisdictions ?? []).map(key));
  const list = (items: string[]) => (items.length ? items.map((l) => `  ${JSON.stringify(l)},\n`).join("") : "");
  return [
    "// GENERATED by scripts/sync-scrapable-platforms.ts from server/scrapers/registry.ts — do not edit by hand.",
    "// Lower-cased permit_databases.platform labels (and aliases) that have a live-search adapter, plus the",
    "// jurisdictions served by a jurisdiction-specific adapter (official open-data feeds). Shared with the client so the",
    "// Search/Directory pages can tell \"searchable here\" from \"link only\" without a server round trip.",
    `export const SCRAPABLE_PLATFORM_LABELS: readonly string[] = [\n${list(listPlatformLabels())}];`,
    `export const ADAPTER_JURISDICTIONS: readonly string[] = [\n${list(listAdapterJurisdictions().filter((j) => !skip.has(j)))}];`,
    "",
    "const labels = new Set(SCRAPABLE_PLATFORM_LABELS);",
    "const jurisdictions = new Set(ADAPTER_JURISDICTIONS);",
    "",
    "export function isScrapablePlatform(platform: string | null | undefined): boolean {",
    "  return !!platform && labels.has(platform.trim().toLowerCase());",
    "}",
    "",
    "export function hasJurisdictionAdapter(jurisdiction: string | null | undefined): boolean {",
    "  return !!jurisdiction && jurisdictions.has(jurisdiction.trim().toLowerCase());",
    "}",
    "",
  ].join("\n");
}

/** Does this platform have an adapter whose listRecent really lists by date? */
export function supportsAlerts(platform: string | null | undefined): boolean {
  return getAdapter(platform)?.capabilities.listRecent === true;
}

/** Map a legacy ScrapeResult (server/scraper.ts) to the normalized record. */
export function fromLegacyResult(r: ScrapeResult, ctx: Pick<AdapterCtx, "databaseId" | "jurisdiction">): PermitRecord | null {
  if (!r.permitNumber) return null;
  const raw = (r as any).rawData as Record<string, unknown> | undefined;
  return {
    permitNumber: r.permitNumber,
    jurisdiction: ctx.jurisdiction,
    databaseId: ctx.databaseId,
    address: r.address ?? null,
    parcel: r.parcelNumber ?? null,
    permitType: r.permitType ?? null,
    description: r.description ?? null,
    status: r.status ?? null,
    issuedAt: r.issuedDate ?? null,
    expiresAt: r.expirationDate ?? null,
    contractorName: r.contractorName ?? null,
    applicantName: r.applicantName ?? null,
    sourceUrl: typeof raw?.detailUrl === "string" ? raw.detailUrl : null,
    raw: raw ?? null,
  };
}

/** The legacy scrapers write search_results rows under a query id; alerts/registry searches use this sentinel. */
export const REGISTRY_QUERY_ID = 0;

function legacy(platform: string, aliases: string[], search: PermitSearchType[]): LegacyAdapter {
  return {
    legacy: true,
    platform,
    aliases,
    capabilities: { search, listRecent: false, detail: false },
    async search(ctx, q) {
      const jobId = `registry-${ctx.databaseId}-${Date.now()}`;
      const results = await scrapeByPlatform(
        platform, ctx.searchUrl, q.value, q.type, ctx.databaseId, ctx.databaseName, REGISTRY_QUERY_ID, jobId,
      );
      return results.map(r => fromLegacyResult(r, ctx)).filter((r): r is PermitRecord => r !== null);
    },
    async listRecent() {
      return [];
    },
  };
}

